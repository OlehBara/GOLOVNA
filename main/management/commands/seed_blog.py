class Command(BaseCommand):
    help = "Seed blog with Ukrainian financial literacy articles"

    def handle(self, *args, **options):
        created_count = 0
        for data in BLOG_POSTS:
            obj, created = BlogPost.objects.get_or_create(
                slug=data["slug"],
                defaults=data,
            )
            if created:
                created_count += 1
                self.stdout.write(self.style.SUCCESS(f"  + {data['title']}"))
            else:
                self.stdout.write(f"  ~ Already exists: {data['title']}")

        self.stdout.write(self.style.SUCCESS(f"\nDone! Created {created_count} blog posts."))
